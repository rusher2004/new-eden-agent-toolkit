// Command genscopes generates esi/scopes_gen.go: the ESI scope every
// authenticated endpoint requires, read from the OpenAPI spec that ships
// inside the goesi-openapi module neat builds against. esi/ checks each
// request against this table, so a tool calling an endpoint its character
// hasn't granted fails with a clear "re-authorize with scope group X" error
// instead of an opaque 403 from ESI.
//
// It is wired via `go:generate` in esi/scopes.go. Rerun `go generate ./...`
// after bumping goesi-openapi; esi's tests fail if a scope in the table
// belongs to no sso scope group.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"

	"github.com/goccy/go-yaml"
)

const goesiModule = "github.com/fnt-eve/goesi-openapi"

type operation struct {
	Security []map[string][]string `yaml:"security"`
}

type spec struct {
	Paths map[string]map[string]operation `yaml:"paths"`
}

type endpoint struct {
	method, path, scope string
}

func main() {
	out := flag.String("out", "scopes_gen.go", "output file")
	flag.Parse()
	if err := run(*out); err != nil {
		fmt.Fprintln(os.Stderr, "genscopes:", err)
		os.Exit(1)
	}
}

func run(out string) error {
	cmd := exec.Command("go", "list", "-m", "-f", "{{.Dir}} {{.Version}}", goesiModule)
	listed, err := cmd.Output()
	if err != nil {
		return fmt.Errorf("locate %s: %w", goesiModule, err)
	}
	dir, version, ok := strings.Cut(strings.TrimSpace(string(listed)), " ")
	if !ok {
		return fmt.Errorf("unexpected go list output %q", listed)
	}

	raw, err := os.ReadFile(filepath.Join(dir, "esi", "api", "openapi.yaml"))
	if err != nil {
		return fmt.Errorf("read spec: %w", err)
	}
	var s spec
	if err := yaml.Unmarshal(raw, &s); err != nil {
		return fmt.Errorf("parse spec: %w", err)
	}

	endpoints, err := collect(s)
	if err != nil {
		return err
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by tools/genscopes from %s %s's esi/api/openapi.yaml. DO NOT EDIT.\n\n", goesiModule, version)
	buf.WriteString("package esi\n\n")
	buf.WriteString("// endpointScopes is the ESI scope each endpoint requires, \"\" for a public one.\n")
	buf.WriteString("var endpointScopes = []endpointScope{\n")
	for _, e := range endpoints {
		fmt.Fprintf(&buf, "\t{%q, %q, %q},\n", e.method, e.path, e.scope)
	}
	buf.WriteString("}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format output: %w", err)
	}
	if err := os.WriteFile(out, src, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", out, err)
	}
	return nil
}

// collect lists every operation with the scope it requires ("" for a
// public one), sorted by path then method so the output is stable. Public
// operations are listed too so that a request matches its own template:
// esi/ picks the most specific match, and without them a public path could
// fall to an authenticated template with the same shape.
func collect(s spec) ([]endpoint, error) {
	var endpoints []endpoint
	for path, ops := range s.Paths {
		for method, op := range ops {
			e := endpoint{method: strings.ToUpper(method), path: path}
			if len(op.Security) > 1 {
				// Several entries are alternatives (any one satisfies the
				// endpoint, e.g. optional auth); esi/ can't express that, and
				// keeping only one would block requests ESI allows.
				return nil, fmt.Errorf("%s %s lists %d alternative security requirements; esi/scopes.go supports one", method, path, len(op.Security))
			}
			for _, req := range op.Security {
				switch scopes := req["OAuth2"]; len(scopes) {
				case 0:
				case 1:
					e.scope = scopes[0]
				default:
					// esi/ checks one scope per endpoint; fail loudly if
					// FC ever starts requiring more than one.
					return nil, fmt.Errorf("%s %s requires %d scopes %v; esi/scopes.go supports one", method, path, len(scopes), scopes)
				}
			}
			endpoints = append(endpoints, e)
		}
	}
	sort.Slice(endpoints, func(i, j int) bool {
		if endpoints[i].path != endpoints[j].path {
			return endpoints[i].path < endpoints[j].path
		}
		return endpoints[i].method < endpoints[j].method
	})
	return endpoints, nil
}
